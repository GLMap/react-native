const { withAppDelegate } = require('expo/config-plugins');

// App-owned opt-in for the pinned Expo 57 blank template, not an SDK plugin.
// The demo/probe app.json declares the matching EXExpoAppSceneDelegate manifest.
const originalClass = 'class AppDelegate: ExpoAppDelegate {';
const sceneClass = 'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {';
const originalStartup = `#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif`;
const sceneStartup = '// ExpoAppSceneDelegate creates the window and starts React Native.';

function migrateAppDelegate(contents, language) {
  if (language !== 'swift') {
    throw new Error('with-expo-scenes supports only the demo\'s Swift AppDelegate');
  }
  // Repeated prebuilds, including hosts generated by the earlier demo, are no-ops.
  if (contents.includes(sceneClass) && contents.includes(sceneStartup)
      && !contents.includes('window = UIWindow(') && !contents.includes('factory.startReactNative(')) {
    return contents;
  }
  if (!contents.includes(originalClass) || !contents.includes(originalStartup)) {
    throw new Error('Unexpected Expo AppDelegate template; configure the app\'s scene lifecycle explicitly');
  }
  // Match only the known startup block: never delete arbitrary code up to #endif.
  return contents.replace(originalClass, sceneClass).replace(originalStartup, sceneStartup);
}

module.exports = config => withAppDelegate(config, config => {
  config.modResults.contents = migrateAppDelegate(config.modResults.contents, config.modResults.language);
  return config;
});
module.exports.migrateAppDelegate = migrateAppDelegate;
